def project_titles():
    titles = {}
    for g in json.loads((ROOT / 'data/work.json').read_text(encoding='utf-8')):
        for p in g.get('projects', []):
            titles[p['slug']] = f"{g.get('short', '')}｜{p.get('short') or p.get('title')}"
    for p in json.loads((ROOT / 'data/projects.json').read_text(encoding='utf-8')):
        if p.get('slug'):
            titles[p['slug']] = f"Quant Lab｜{p['name']}"
    return titles


